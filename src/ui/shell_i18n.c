const char *tt(shell_lang lang, const char *key) {
    int n = (int)(sizeof UI_STRINGS / sizeof UI_STRINGS[0]);
    int idx = lang == UI_EN ? 2 : 1;
    for (int i = 0; i < n; i++)
        if (osa_streq(UI_STRINGS[i][0], key)) return UI_STRINGS[i][idx];
    return key;
}
