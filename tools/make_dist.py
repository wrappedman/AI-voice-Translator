#!/usr/bin/env python3
"""Package the Windows build for release.

Produces dist/OpenSpeechAI-<version>-win64.zip containing the exe, the licence
and a short readme, plus SHA-256 sums for both the zip and the bare exe.
"""
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def version() -> str:
    """The version lives in exactly one place: src/core/osai_common.h.
    The zip name, the readme and the checksum file all come from it, so a
    release cannot end up with a 1.0.0 file name and a 1.1.0 binary."""
    with open(os.path.join(ROOT, "src", "core", "osai_common.h"), encoding="utf-8") as f:
        m = re.search(r'#define\s+OSAI_VERSION\s+"([0-9.]+)"', f.read())
    if not m:
        raise SystemExit("cannot read OSAI_VERSION from src/core/osai_common.h")
    return m.group(1)


VERSION = version()
DIST = os.path.join(ROOT, "dist")
EXE = os.path.join(DIST, "bin", "OpenSpeechAI.exe")
OUT = os.path.join(DIST, "OpenSpeechAI-%s-win64.zip" % VERSION)

# Everything the executable opens at run time. The fonts used to be left out of
# the release, which meant a fresh copy of the zip started with no text at all
# until the user copied src/ui/assets by hand. `make dist` now lays them out next
# to the exe (assets/fonts/…) and zips that whole tree.
ASSET_FILES = [
    ("src/ui/assets/Vazirmatn-Regular.ttf", "assets/fonts/Vazirmatn-Regular.ttf"),
    ("src/ui/assets/Vazirmatn-Medium.ttf", "assets/fonts/Vazirmatn-Medium.ttf"),
    ("src/ui/assets/Vazirmatn-Bold.ttf", "assets/fonts/Vazirmatn-Bold.ttf"),
    ("src/ui/assets/Vazirmatn-OFL.txt", "assets/fonts/OFL-Vazirmatn.txt"),
    ("tools/catalog/catalog.json", "assets/catalog.json"),
    ("README.md", "README.md"),
    ("docs/ARCHITECTURE.md", "docs/ARCHITECTURE.md"),
    ("docs/MODEL_FORMAT.md", "docs/MODEL_FORMAT.md"),
]

# The models the build ships with, written by the same code the application uses
# (tools/export_models.py runs the headless binary). A copy of the executable
# therefore starts with a working speech and translation model in its data
# folder: `dist/` holds every file the program needs, which is the rule this
# release is built around.
SEED_FILES = [
    ("dist/models/builtin-asr-fa.osam", "models/builtin-asr-fa.osam"),
    ("dist/models/builtin-mt.osmt", "models/builtin-mt.osmt"),
]

README = """OpenSpeech AI {ver} — Windows x64
================================

Portable, fully offline speech recognition (Persian + English) and
Persian<->English translation. No installer, no runtime, no network access.

Run
    OpenSpeechAI.exe

Keep the whole folder together
    OpenSpeechAI.exe needs the assets folder that sits next to it:

        OpenSpeechAI.exe
        assets\\fonts\\Vazirmatn-*.ttf
        assets\\catalog.json
        models\\builtin-asr-fa.osam
        models\\builtin-mt.osmt

    Move the folder as a unit, or unpack the zip somewhere writable. If the
    fonts are missing the program says so instead of starting blank.

The program creates its data folder on first start:
    %LOCALAPPDATA%\\OpenSpeechAI

Everything (models, transcripts, audio copies) stays inside that folder.
Settings are stored in settings.ini next to the data root.

Requirements
    Windows 10 or 11, 64-bit. 350 MB RAM, ~50 MB free disk.

Verified
    SHA-256 of OpenSpeechAI.exe is listed in checksums-{ver}.txt

Licence
    GPL-3.0-or-later. Bundled fonts: Vazirmatn (SIL OFL 1.1), see
    assets\\fonts\\OFL-Vazirmatn.txt
""".format(ver=VERSION)


def write_rc_header() -> None:
    """The Windows version resource is generated from OSAI_VERSION.

    It used to be hand-written with 1.0.0 constants while the application header
    said 1.1.0, so Explorer showed 1.0.0.0 for a 1.1.0 binary - a release whose
    own file properties disagree with it. The resource file now includes this
    generated header instead of keeping its own numbers.
    """
    parts = (VERSION.split(".") + ["0", "0", "0", "0"])[:4]
    if not all(p.isdigit() for p in parts):
        raise SystemExit("OSAI_VERSION must be numeric, got %r" % VERSION)
    path = os.path.join(ROOT, "src", "platform", "win32", "app_version.h")
    body = (
        "/* Generated by tools/make_dist.py from OSAI_VERSION. Do not edit. */\n"
        "#ifndef OSAI_APP_VERSION_RESOURCE_H\n"
        "#define OSAI_APP_VERSION_RESOURCE_H\n"
        "#define OSAI_VER_MAJOR %s\n#define OSAI_VER_MINOR %s\n"
        "#define OSAI_VER_PATCH %s\n#define OSAI_VER_BUILD %s\n"
        "#define OSAI_VERSION_STR \"%s\"\n"
        "#endif\n"
    ) % (parts[0], parts[1], parts[2], parts[3], VERSION)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> int:
    write_rc_header()
    if not os.path.exists(EXE):
        print("missing %s — run `make win` first" % EXE, file=sys.stderr)
        return 1
    os.makedirs(os.path.join(ROOT, "dist"), exist_ok=True)

    files = []
    licence = os.path.join(ROOT, "LICENSE")
    if os.path.exists(licence):
        files.append((licence, "LICENSE.txt"))

    missing = []
    # The models ship too: a copy of dist/ has to work on a machine that never
    # ran the program, so the containers are produced by tools/export_models.py
    # and copied here rather than being built on the user's first start.
    for src, arc in ASSET_FILES + SEED_FILES:
        full = os.path.join(ROOT, src.replace("/", os.sep))
        if os.path.exists(full):
            files.append((full, arc))
        else:
            missing.append(src)
    if missing:
        print("missing required files: %s" % ", ".join(missing), file=sys.stderr)
        print("run `make linux && python3 tools/export_models.py` first", file=sys.stderr)
        return 1

    # Also lay the tree out under dist/bin so the shipped executable can be run
    # straight out of the repository without unpacking the zip.
    bin_dir = os.path.dirname(EXE)
    for src, arc in ASSET_FILES + SEED_FILES:
        full = os.path.join(ROOT, src.replace("/", os.sep))
        if not os.path.exists(full):
            continue
        dst = os.path.join(bin_dir, arc.replace("/", os.sep))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(full, dst)

    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        z.write(EXE, "OpenSpeechAI.exe")
        for src, arc in files:
            z.write(src, arc)
        z.writestr("README.txt", README)

    exe_hash = sha256(EXE)
    zip_hash = sha256(OUT)
    sums = os.path.join(ROOT, "dist", "checksums-%s.txt" % VERSION)
    # Paths are relative to dist/, so `cd dist && sha256sum -c checksums-<v>.txt`
    # works. A bare "OpenSpeechAI.exe" is not in that directory (the binary is
    # under bin/), which made the list look correct but verify as missing.
    with open(sums, "w", encoding="utf-8") as f:
        f.write("%s  bin/OpenSpeechAI.exe\n" % exe_hash)
        f.write("%s  %s\n" % (zip_hash, os.path.basename(OUT)))
    # Nothing may be missing from the layout either: the rule this release is
    # built around is that dist/ holds every file the program needs, so the
    # check runs against the tree that is about to be shipped, not just the zip.
    absent = [arc for _, arc in ASSET_FILES + SEED_FILES
              if not os.path.exists(os.path.join(bin_dir, arc.replace("/", os.sep)))]
    if absent:
        print("dist/bin is missing: %s" % ", ".join(absent), file=sys.stderr)
        return 1
    print("layout: dist/bin has %d files next to the exe (fonts, catalogue, models, docs)"
          % len(ASSET_FILES + SEED_FILES))
    print("zip   : %s (%.1f MB)" % (OUT, os.path.getsize(OUT) / 1048576))
    print("sha256: %s" % zip_hash)
    print("exe   : %s" % exe_hash)
    return 0


if __name__ == "__main__":
    # `--rc-only` is what the Makefile calls before compiling the Windows
    # resource: the version numbers must exist before the exe is linked, and
    # regenerating them at `make win` time is what keeps them honest.
    if "--rc-only" in sys.argv:
        write_rc_header()
        print("version resource: %s" % VERSION)
        sys.exit(0)
    sys.exit(main())
