#!/usr/bin/env python3
"""Generate src/engines/pronounce_fold.h.

Pronounce tables in src/engines/pronounce.c are keyed on the *unaccented* letter
(d, not đ; s, not ś), so one table covers "dziękuję" as well as "dziekuje". This
script emits the mapping from an accented Latin code point to its base letter,
using Unicode normalisation, so the table is not hand-maintained.

    python3 tools/gen_pronounce_fold.py
"""
import unicodedata

HEAD = '''/* Generated by tools/gen_pronounce_fold.py — do not edit by hand.
 *
 * fold_latin(): the base letter of an accented Latin character. The pronunciation
 * tables are keyed on the base letter so that "dziękuję", "dziekuje" and
 * "DZIĘKUJĘ" all read through the same rules, and a language does not need a
 * table entry for every accented form it can appear in. */
#ifndef OSAI_PRONOUNCE_FOLD_H
#define OSAI_PRONOUNCE_FOLD_H
#include <stdint.h>

typedef struct pron_fold { uint16_t cp; uint8_t base; } pron_fold;

static const pron_fold PRON_FOLD[] = {
'''

TAIL = '''};

/* Base letter of `cp` (ASCII 'a'..'z'), or 0 when it is not a folded Latin
 * letter. */
static inline char fold_latin(uint32_t cp) {
    if (cp < 0x80) return (char)cp;
    for (unsigned i = 0; i < sizeof PRON_FOLD / sizeof PRON_FOLD[0]; i++)
        if (PRON_FOLD[i].cp == cp) return (char)(PRON_FOLD[i].base + 'a');
    return 0;
}

#endif
'''

def main():
    out = []
    for cp in list(range(0xC0, 0x250)) + list(range(0x1E00, 0x1F00)):
        d = unicodedata.normalize("NFD", chr(cp))
        if len(d) > 1 and d[0].isascii() and d[0].isalpha():
            out.append("    {0x%04X, %d}," % (cp, ord(d[0].lower()) - 97))
    with open("src/engines/pronounce_fold.h", "w") as f:
        f.write(HEAD + "\n".join(out) + "\n" + TAIL)

if __name__ == "__main__":
    main()
